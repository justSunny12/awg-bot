    return (f"✅ Второй интерфейс поднят: {_e(res['iface'])}, <code>{_e(res['subnet'])}</code>"
            + (f", порт {_e(str(res['port']))}" if res.get("port") else "")
            + " · после перезапуска бота: 🔧 Сервис → 🚚 Начать переезд")
