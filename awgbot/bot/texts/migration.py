def migration_promoted(iface: str, dns: str = "") -> str:
    """Финал переезда: новый интерфейс стал основным, нужен рестарт."""
    return (f"🚚 Переезд завершён: основным интерфейсом стал <code>{_e(iface)}</code>, "
            "новые устройства рождаются на нём. Старый опущен и снят с автозагрузки, "
            "его конфиг оставлен на всякий случай."
            + (f"\n🔒 DNS клиентов — свой резолвер <code>{_e(dns)}</code>." if dns else "")
            + "\n\nПерезапускаю бота — деплой-значения читаются при старте.")


def migration_promote_restart_failed() -> str:
    return ("⚠️ Перезапустить бота автоматически не вышло. Сделай это сам: "
            "<code>sudo awg-bot restart</code> — до рестарта основным считается "
            "прежний интерфейс, и новые устройства родятся на нём.")


_LIST_CAP = 20


def _rows_capped(rows) -> str:
    """Список «профиль — устройство» с пределом: экран не отчёт, а лимит
    Telegram — 4096 знаков."""
    lines = [f"• {_e(client)} — {_e(device)}" for client, device in list(rows)[:_LIST_CAP]]
    if len(rows) > _LIST_CAP:
        lines.append(f"• … и ещё {len(rows) - _LIST_CAP}")
    return "\n".join(lines)


def _names_capped(names) -> str:
    names = list(names)
    return ", ".join(_e(n) for n in names[:_LIST_CAP]) + (f" и ещё {len(names) - _LIST_CAP}" if len(names) > _LIST_CAP else "")


def migration_pending_text(rows) -> str:
    """Кто ещё не переехал, поимённо."""
    if not rows:
        return "✅ Непереехавших нет — все живые устройства уже на новом интерфейсе"
    lines = _rows_capped(rows)
    return (f"🚚 Ещё не переехали ({len(rows)})\n{lines}\n"
            "Каждому нужно переимпортировать конфиг: он выдаётся обычным путём, старый пир до "
            "завершения продолжает работать")


def migration_start_confirm(clients: int, devices: int, to_birth: int) -> str:
    """Подтверждение старта: с этой секунды меняется выдача, и знаменатель
    готовности замораживается здесь же."""
    return (f"🚚 Начать переезд? Новых профилей: {to_birth}. В учёт готовности: {clients} профилей, "
            f"{devices} устройств. С этой секунды выдаются только новые конфиги; старые работают")


def migration_finish_confirm(dropped) -> str:
    """Уронённых называем поимённо, а не числом."""
    if not dropped:
        return "🚚 Завершить? Все живые устройства уже на новом интерфейсе. Старые пиры снимутся, история сольётся"
    names = _names_capped(dropped)
    return (f"🚚 Завершить? Потеряют связь сейчас ({len(dropped)}): {names}. Вернуть — выдать конфиг заново. "
            "Старые пиры снимутся, история сольётся")


def migration_cancel_confirm(moved: int) -> str:
    if not moved:
        return "🚚 Отменить? Перейти никто не успел — всё вернётся ровно как было"
    return (f"🚚 Отменить? Переехали {moved} — их соединения не оборвутся, выдаваться снова будут "
            "старые конфиги; переехавшие соберутся списком в «🔧 Сервис»")


def migration_orphans_text(rows) -> str:
    """Двойники, пережившие отмену."""
    if not rows:
        return "Переехавших после отмены нет"
    lines = _rows_capped(rows)
    return (f"⚠️ Переехали до отмены ({len(rows)})\n{lines}\n"
            "Их соединения живы, но выдаются снова старые конфиги: вернуть на старый или включить переезд снова")


def migration_cancelled(moved: int) -> str:
    if not moved:
        return "↩️ Переезд отменён — всё как было: выдаются старые конфиги, новые профили не востребованы"
    return (f"↩️ Переезд отменён · переехали {moved}, их соединения не оборваны; выдаются старые конфиги, "
            "переехавшие — списком в «🔧 Сервис»")


def migration_finished(removed: int, dropped, failed=()) -> str:
    """Итог завершения: первые строки открыто, что делать руками — под «подробнее»."""
    from .fmt import details
    if failed:
        return (f"⚠️ Завершено не до конца: снято пиров {removed}, не закрыто {len(failed)} — сервер не дал "
                "снять пира: " + _names_capped(failed)
                + ". Рычаг оставлен включённым, повтори завершение — доберутся только они")
    head = f"✅ Переезд завершён · старых пиров снято: {removed}"
    if dropped:
        head += (f"\n⚠️ Потеряли связь ({len(dropped)}): " + _names_capped(dropped)
                 + " — вернуть значит выдать конфиг заново")
    return head + "\nДальше руками на сервере" + details(
        "1. снять старый интерфейс и его юнит;\n"
        "2. убрать DNAT 1.1.1.1 и закрыть старый порт;\n"
        "3. переключить docker.interface и network.subnet_prefix в app.yaml на новые и перезапустить "
        "бота — без этого вотчдог смотрит на мёртвый конфиг, preflight проверяет снесённый интерфейс, "
        "новые устройства получают адреса из подсети, которой нет;\n"
        "4. вычистить старую подсеть из того, что её помнит: Match Address в sshd_config (обе строки), "
        "набор ssh_allow4, правила хоста для DNS и MASQUERADE;\n"
        "5. если стоит шлюз — сменить клиентскую подсеть на обеих его сторонах одним заходом: исключение "
        "из MASQUERADE на сервере AWG, на шлюзе — его MASQUERADE и AllowedIPs линка; иначе, как только "
        "исключение сработает, шлюз увидит настоящие адреса клиентов и не покроет их — российские "
        "сервисы перестанут открываться")


def migration_prepare_intro(d: dict) -> str:
    """Экран перед переездом: что сменится и чего это стоит."""
    from .fmt import details
    port = f"порт {d['want_port']}" if d.get("want_port") else "случайный высокий порт"
    dns = ", DNS клиентов — свой резолвер" if d.get("private_dns") else ""
    return (f"🚚 Порт или подсеть · сейчас {_e(d['iface'])}, {d['port']}, {_e(d['subnet'])} → новый интерфейс, "
            f"{port}, свободная подсеть{dns} · в переезд войдут {d['devices']} "
            f"{plural_ru(d['devices'], 'устройство', 'устройства', 'устройств')} у {d['clients']} "
            f"{plural_ru(d['clients'], 'профиля', 'профилей', 'профилей')} (были онлайн за 2 недели)"
            + details("порт и подсеть вморожены в каждую ссылку, поэтому меняются переездом: рядом со старым "
                      "интерфейсом поднимается новый, у каждого устройства рождается двойник · старые пиры "
                      "работают до финала, никто не отваливается в момент старта · новые конфиги выдаются "
                      "сразу, люди переносят их когда удобно · отмена безопасна в любой момент · на финале "
                      "непереехавшие теряют связь, бот назовёт их поимённо до нажатия"))


