def migration_promoted(iface: str, dns: str = "") -> str:
    """Финал переезда: новый интерфейс стал основным, нужен рестарт."""
    return (f"🚚 Переезд завершён: основным интерфейсом стал <code>{_e(iface)}</code>, "
            "новые устройства рождаются на нём. Старый опущен и снят с автозагрузки, "
            "его конфиг оставлен на всякий случай."
            + (f"\n🔒 DNS клиентов — свой резолвер <code>{_e(dns)}</code>." if dns else "")
            + "\n\nДеплой-значения читаются при старте — нужен перезапуск бота")


_LIST_CAP = 20


def _rows_capped(rows) -> str:
    """Список «профиль — устройство» с пределом: экран не отчёт, а лимит
    Telegram — 4096 знаков."""
    lines = [f"• {_e(client)} — {_e(device)}" for client, device in list(rows)[:_LIST_CAP]]
    if len(rows) > _LIST_CAP:
        lines.append(f"• … и ещё {len(rows) - _LIST_CAP}")
    return "\n".join(lines)


def _names_capped(names) -> str:
    names = list(names)
    return ", ".join(_e(n) for n in names[:_LIST_CAP]) + (f" и ещё {len(names) - _LIST_CAP}" if len(names) > _LIST_CAP else "")


def migration_pending_text(rows) -> str:
    """Кто ещё не переехал, поимённо."""
    if not rows:
        return "✅ Непереехавших нет — все живые устройства уже на новом интерфейсе"
    lines = _rows_capped(rows)
    return (ui.head("🚚 Ещё не переехали", f"({len(rows)})") + f"\n{lines}\n"
            "Каждому нужно переимпортировать конфиг: он выдаётся обычным путём, старый пир до "
            "завершения продолжает работать")


def migration_start_confirm(clients: int, devices: int, to_birth: int) -> str:
    """Подтверждение старта: с этой секунды меняется выдача, и знаменатель
    готовности замораживается здесь же."""
    return (f"🚚 Начать переезд? Новых профилей: {to_birth}. В учёт готовности: {clients} "
            f"{plural_ru(clients, 'профиль', 'профиля', 'профилей')}, {devices} "
            f"{plural_ru(devices, 'устройство', 'устройства', 'устройств')}. "
            "С этой секунды будут выдаваться только новые конфиги; старые продолжат работать "
            "до окончания переезда")


def migration_finish_confirm(dropped) -> str:
    """Уронённых называем поимённо, а не числом."""
    if not dropped:
        return "🚚 Завершить переезд? Все живые устройства уже на новом интерфейсе. Старые пиры снимутся, история объединится"
    names = _names_capped(dropped)
    return (f"🚚 Завершить переезд? Потеряют связь сейчас ({len(dropped)}): {names}. Вернуть — перенастроить "
            "устройство с новой конфигурацией. Старые пиры снимутся, история объединится")


def migration_cancel_confirm(moved: int) -> str:
    if not moved:
        return "🚚 Отменить переезд? Перейти никто не успел — всё вернётся ровно как было"
    return (f"🚚 Отменить переезд? Успели переехать {moved} — их соединения не оборвутся, при следующей "
            "настройке устройств им будут выданы старые конфиги; переехавшие соберутся списком в «🔧 Сервис»")


def migration_orphans_text(rows) -> str:
    """Двойники, пережившие отмену."""
    if not rows:
        return "Переехавших после отмены нет"
    lines = _rows_capped(rows)
    return (ui.head("⚠️ Переехали до отмены", f"({len(rows)})") + f"\n{lines}\n"
            "Их соединения живы, но выдаются снова старые конфиги: перед удалением интерфейса под "
            "переезд необходимо вернуть пользователей на старые настройки")


def migration_cancelled(moved: int) -> str:
    if not moved:
        return "↩️ Переезд отменён — изменения откачены: выдаются старые конфиги, влияния на пользователей нет"
    return (f"↩️ Переезд отменён · успели переехать {moved}, их соединения не оборваны; выдаются старые конфиги, "
            "переехавшие — списком в «🔧 Сервис»")


def migration_finished(removed: int, dropped, failed=()) -> str:
    """Итог завершения: первые строки открыто, что делать руками — под «подробнее»."""
    from .fmt import details
    if failed:
        return (f"⚠️ Завершено не до конца: снято пиров {removed}, не закрыто {len(failed)} — сервер не дал "
                "снять пир: " + _names_capped(failed)
                + ". Рычаг оставлен включённым, повтори завершение — доберутся только они")
    head = f"✅ Переезд завершён · старых пиров снято: {removed}"
    if dropped:
        head += (f"\n⚠️ Потеряли связь ({len(dropped)}): " + _names_capped(dropped)
                 + " — вернуть можно повторной настройкой устройства")
    # старый интерфейс и его юнит, app.yaml — завершение делает само
    # (migration_finish); здесь — то, чего бот на хосте не знает
    return head + "\nПроверь на сервере" + details(
        "1. DNAT <code>1.1.1.1</code> и старый порт — убрать и закрыть;\n"
        "2. старая подсеть там, где её помнят: Match Address в sshd_config (обе строки), "
        "набор ssh_allow4, правила хоста для DNS и MASQUERADE;\n"
        "3. если стоит шлюз — сменить клиентскую подсеть на обеих его сторонах одним заходом: исключение "
        "из MASQUERADE на сервере AWG, на шлюзе — его MASQUERADE и AllowedIPs линка; иначе, как только "
        "исключение сработает, шлюз увидит настоящие адреса клиентов и не покроет их — российские "
        "сервисы перестанут открываться")


def migration_prepare_intro(d: dict) -> str:
    """Экран перед переездом: что сменится и чего это стоит."""
    from .fmt import details
    port = f"порт {d['want_port']}" if d.get("want_port") else "случайный высокий порт"
    dns = ", DNS клиентов — свой резолвер" if d.get("private_dns") else ""
    return (ui.head("🚚 Порт или подсеть", meta=[f"сейчас: {_e(d['iface'])}, {d['port']}, <code>{_e(d['subnet'])}</code>"]) + "\n\n"
            f"Новый интерфейс, {port}, свободная подсеть{dns}\n"
            f"В переезд {plural_ru(d['devices'], 'войдёт', 'войдут', 'войдут')} {d['devices']} "
            f"{plural_ru(d['devices'], 'устройство', 'устройства', 'устройств')} у {d['clients']} "
            f"{plural_ru(d['clients'], 'профиля', 'профилей', 'профилей')} (были онлайн за 2 недели; у остальных "
            "доступ пропадёт после окончания переезда — до перенастройки устройств)"
            + details("порт и подсеть вморожены в каждую ссылку, поэтому меняются переездом: рядом со старым "
                      "интерфейсом поднимается новый, у каждого устройства рождается двойник;\n"
                      "новые настройки выдаются с момента начала переезда — пользователи перенастраивают "
                      "устройства, когда им удобно;\n"
                      "старые пиры работоспособны до завершения переезда · отмена безопасна в любой момент;\n"
                      "при завершении переезда старые пиры удаляются, непереехавшие теряют связь — бот назовёт "
                      "их поимённо до нажатия · созданные ранее двойники на новом интерфейсе остаются — поэтому "
                      "возможность переехать сохраняется"))


