def migration_prepared(res: dict) -> str:
    return (f"✅ Второй интерфейс поднят: <code>{_e(res['iface'])}</code>, "
            f"подсеть <code>{_e(res['subnet'])}</code>"
            + (f", порт {_e(str(res['port']))}" if res.get("port") else "") + ".\n\n"
            "Перезапускаю бота — имя интерфейса читается при старте. После этого "
            "начни переезд: ⚙️ Настройки → 🔄 Обслуживание → «🚚 Начать переезд "
            "профилей».")


def migration_prepare_failed(reason: str) -> str:
    return ("⚠️ Второй интерфейс не поднят.\n\n<pre>" + _e(str(reason)[-900:]) + "</pre>\n\n"
            "Ничего наполовину не осталось: конфиг бота не тронут, старый "
            "интерфейс работает как работал.")


