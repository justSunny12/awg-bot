def migration_promoted(iface: str, dns: str = "") -> str:
    """Завершение переезда: новый интерфейс стал основным, нужен рестарт."""
    return (f"🚚 Основным интерфейсом стал <code>{_e(iface)}</code> — новые устройства "
            "создаются на нём. Старый остановлен и снят с автозагрузки, его конфиг сохранён "
            "на всякий случай"
            + (f"\n🔒 DNS пользователей — свой резолвер <code>{_e(dns)}</code>" if dns else "")
            + "\n\nПараметры интерфейса бот читает при старте — нужен перезапуск")


_LIST_CAP = 20


def _rows_capped(rows) -> str:
    """Список «профиль — устройство» с пределом: экран не отчёт, а лимит
    Telegram — 4096 знаков."""
    lines = [f"• {_e(client)} — {_e(device)}" for client, device in list(rows)[:_LIST_CAP]]
    if len(rows) > _LIST_CAP:
        lines.append(f"• … и ещё {len(rows) - _LIST_CAP}")
    return "\n".join(lines)


def _names_capped(names, bot: str = "") -> str:
    """Имена через запятую; больше _LIST_CAP — «и ещё N» (с именем бота —
    ссылкой на экран «🚚 Потеряют связь при завершении»)."""
    from awgbot.util.textfmt import more_link
    names = list(names)
    out = ", ".join(_e(n) for n in names[:_LIST_CAP])
    more = len(names) - _LIST_CAP
    if more > 0:
        out += more_link(more, bot, "list-migdrop") if bot else f" и ещё {more}"
    return out


def migration_pending_text(rows) -> str:
    """Кто ещё не переехал, поимённо."""
    if not rows:
        return "✅ Непереехавших нет — все недавно активные устройства уже на новом интерфейсе"
    lines = _rows_capped(rows)
    return (ui.head("🚚 Ещё не переехали", meta=[f"из недавно активных ({len(rows)})"]) + f"\n{lines}\n"
            "Каждому нужно заново получить конфигурацию — ссылкой, QR или файлом — и импортировать её; "
            "прежняя работает до завершения переезда")


