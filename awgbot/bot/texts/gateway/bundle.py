from __future__ import annotations

from awgbot.bot import ui
from ..fmt import _e


# Бэкап в чате агента — любой (шлюза прежних версий или сервера): своих копий у
# шлюза нет, настройки едут с сервера AWG по каналу конфигурации
GW_OLD_BACKUP_REFUSED = ("⚠️ Бэкап шлюза не применён: настройки шлюза теперь хранятся в бэкапе сервера AWG, "
                         "а новое устройство получает их по каналу конфигурации. Файл убран из чата — в нём ключи")


def host_rebooted(hostname: str, who: str) -> str:
    """«Шлюз pi перезагрузился — бот снова на связи» — после всех проверок
    старта; who — «бота» (сервер AWG) / «агента» (шлюз): функция общая двум
    ролям, развилка по тому, кто запустился."""
    if who == "агента":
        return f"⚠️ Шлюз {_e(hostname)} перезагрузился — бот снова на связи"
    return "⚠️ Сервер AWG перезагрузился — бот снова на связи"


def gw_confirm_reassert(carries: bool = True) -> str:
    return ("🚑 Восстановить шлюз?\nБот переставит правила шлюза (маскарад, изоляция, метка) и "
            "переподнимет линк" + (" — РФ-доступ у всех прервётся на секунды" if carries else ""))


# Файл конфигурации шлюза в чате агента — любой (первого применения или
# шифрованный перевыпуск прежних выпусков): конфигурацию шлюз получает только по
# каналу конфигурации (формулировка пользователя 17.10.2026)
GW_REISSUE_FILE_REFUSED = ("⚠️ Файл конфигурации не применён: этот шлюз автоматически получает настройки "
                           "от сервера AWG по каналу конфигурации. Сообщение с файлом из чата убрал: внутри ключи")


def gateway_op_result(done: str, failed: str, ok: bool, detail: str, hint: str = "") -> str:
    """«✅ Шлюз восстановлен» / «⚠️ Шлюз не восстановлен» (действие не
    выполнено — ⚠️, не 🔴) + деталь моноширинным; hint — следующий шаг при
    отказе, строкой ниже."""
    head = ui.head(f"✅ {done}" if ok else f"⚠️ {failed}")
    text = head + (f"\n<code>{_e(detail)}</code>" if detail else "")
    return text + (f"\n{hint}" if hint and not ok else "")


