# Бэкап в чате агента — любой (шлюза прежних версий или сервера): своих копий у
# шлюза нет, настройки едут с сервера AWG по каналу конфигурации
GW_OLD_BACKUP_REFUSED = ("⚠️ Бэкап шлюза не применён: настройки шлюза теперь хранятся в бэкапе сервера AWG, "
                         "а новое устройство получает их по каналу конфигурации. Файл убран из чата — в нём ключи")
# бэкап сервера AWG в чате шлюза — серверу по каналу (вторая точка входа восстановления)
GW_RELAY_SENDING = "⏳ Передаю бэкап серверу AWG…"
GW_RELAY_BUSY = ("⏳ Уже передаю бэкап серверу AWG — дождись окончания. Если восстановление из прошлого файла "
                 "не требуется, сможешь отказаться после завершения передачи")
_TERMINAL = "<code>sudo awg-bot restore &lt;файл&gt;</code>"


def gw_relay_result(res: dict, server_bot: dict | None) -> str:
    """Итог передачи — правкой «⏳ Передаю…»: принят — где продолжать; отказ
    сервера — его словами (в причине уже есть следующий шаг, если он есть);
    канала нет, сервер старше, обрыв, большой файл — что делать."""
    from awgbot.domain.notices.backup import chat_ref
    bot = chat_ref(server_bot, "бота сервера AWG")
    why = str(res.get("why") or "")
    if res.get("ok"):
        return f"✅ Бэкап передан: продолжи в чате {bot}"
    if why == "refused":
        reason = _e(str(res.get("error") or "отказ без причины"))
        reason = reason.replace(_e("sudo awg-bot restore <файл>"), _TERMINAL)
        if reason.endswith("в чат бота сервера"):                 # ссылку на бота сервера знает агент
            reason = reason[:-len("бота сервера")] + chat_ref(server_bot, "бота сервера")
        return f"⚠️ Бэкап не принят сервером AWG: {reason}"
    if why == "broken":
        return (f"⚠️ Передать бэкап не удалось: связь с сервером AWG оборвалась — пришли файл снова (или "
                f"напрямую в чат {bot})")
    if why == "broken_after":
        return (f"⚠️ Связь с сервером AWG оборвалась после передачи — проверь чат {bot}: если диалога о "
                "восстановлении нет — пришли файл снова")
    if why == "no_cap":
        return (f"⚠️ Передать бэкап не удалось: версия сервера AWG старше 3.4.0 и бэкапы через шлюз не "
                f"принимает — пришли бэкап в чат {bot} или восстанови на сервере: {_TERMINAL}")
    if why == "big":
        return f"⚠️ Передать бэкап не удалось: он больше 20 МБ — восстанови на сервере: {_TERMINAL}"
    return (f"⚠️ Передать бэкап не удалось: сервер AWG сейчас не на связи — пришли бэкап в чат {bot} или "
            f"восстанови на сервере: {_TERMINAL}")


def host_rebooted(hostname: str, who: str) -> str:
    """«Шлюз pi перезагрузился — бот снова на связи» — после всех проверок
    старта; who — «бота» (сервер AWG) / «агента» (шлюз): функция общая двум
    ролям, развилка по тому, кто запустился."""
    if who == "агента":
        return f"⚠️ Шлюз {_e(hostname)} перезагрузился — бот снова на связи"
    return "⚠️ Сервер AWG перезагрузился — бот снова на связи"


def gw_confirm_reassert(carries: bool = True) -> str:
    return ("🚑 Восстановить шлюз?\nБот переставит правила шлюза (маскарад, изоляция, метка) и "
            "переподнимет линк" + (" — РФ-доступ у всех прервётся на секунды" if carries else ""))


# Файл конфигурации шлюза в чате агента — любой (первого применения или
# шифрованный перевыпуск прежних выпусков): файлов больше нет, шлюзы
# подключаются командой из бота сервера
GW_REISSUE_FILE_REFUSED = ("⚠️ Файл конфигурации не применён: этот шлюз автоматически получает настройки от сервера "
                           "AWG по каналу конфигурации. Сообщение с файлом из чата убрал: внутри ключи")


def gateway_op_result(done: str, failed: str, ok: bool, detail: str, hint: str = "") -> str:
    """«✅ Шлюз восстановлен» / «⚠️ Шлюз не восстановлен» (действие не
    выполнено — ⚠️, не 🔴) + деталь моноширинным; hint — следующий шаг при
    отказе, строкой ниже."""
    head = ui.head(f"✅ {done}" if ok else f"⚠️ {failed}")
    text = head + (f"\n<code>{_e(detail)}</code>" if detail else "")
    return text + (f"\n{hint}" if hint and not ok else "")


