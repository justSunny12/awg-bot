"""bundle.py — часть пакета gateway (см. __init__): файлы в чате агента, восстановление, перезагрузка."""
from __future__ import annotations

from awgbot.bot import ui
from ..fmt import _e


GW_BACKUP_NO_KEY = ("💾 Бэкап шлюза — только шифрованный: в копии приватные ключи линка и туннеля. "
                    "Задай фразу в «🔐 Шифрование»")


def host_rebooted(hostname: str, who: str) -> str:
    """«Шлюз pi перезагрузился — бот снова на связи» — после всех проверок
    старта; who — «бота» (сервер AWG) / «агента» (шлюз): функция общая двум
    ролям, развилка по тому, кто запустился."""
    if who == "агента":
        return f"⚠️ Шлюз {_e(hostname)} перезагрузился — бот снова на связи"
    return "⚠️ Сервер AWG перезагрузился — бот снова на связи"


def gw_confirm_reassert(carries: bool = True) -> str:
    return ("🚑 Восстановить шлюз?\nБот переставит правила шлюза (маскарад, изоляция, метка) и "
            "переподнимет линк" + (" — РФ-доступ у всех прервётся на секунды" if carries else ""))


def gw_first_run_file(name: str = "awg-gw-bundle.sh") -> str:
    """Прислан файл конфигурации шлюза (файл первого применения) — под тем
    именем, под каким прислали: команда с чужим именем файла у человека бы не
    нашлась. Агент уже стоит, поэтому без `--install`, как просит и
    установщик; агент старше файла — файл сам скажет запустить с `--install`."""
    return ("⚠️ Это файл конфигурации шлюза — его не присылают боту, а запускают в терминале шлюза: "
            f"<code>sudo sh {_e(name or 'awg-gw-bundle.sh')}</code>. Из чата убрал: внутри ключи")


def gw_bundle_not_ours() -> str:
    """Прислан не тот файл: конфигурацию шлюз получает по каналу конфигурации."""
    return ("⚠️ Это не конфигурация шлюза — файл не принят. "
            "Конфигурацию этот шлюз получает от бота сервера AWG по каналу конфигурации")


# Шифрованный файл перевыпуска выпусков до 3.3.1 (старое сообщение в чате
# бота сервера AWG): не применяется — конфигурация идёт по каналу
GW_REISSUE_FILE_REFUSED = ("⚠️ Файл конфигурации не применён: этот шлюз получает конфигурацию по каналу "
                           "конфигурации от бота сервера AWG. Не встала на шлюзе — «🚑 Восстановить»; "
                           "канал не на связи — «🔧 Канал конфигурации» на главном экране. "
                           "Из чата убрал: внутри ключи")


def gateway_op_result(done: str, failed: str, ok: bool, detail: str, hint: str = "") -> str:
    """«✅ Шлюз восстановлен» / «⚠️ Шлюз не восстановлен» (действие не
    выполнено — ⚠️, не 🔴) + деталь моноширинным; hint — следующий шаг при
    отказе, строкой ниже."""
    head = ui.head(f"✅ {done}" if ok else f"⚠️ {failed}")
    text = head + (f"\n<code>{_e(detail)}</code>" if detail else "")
    return text + (f"\n{hint}" if hint and not ok else "")


