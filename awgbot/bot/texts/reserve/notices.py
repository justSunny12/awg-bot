"""notices.py — тексты уведомлений резерва слоя бота: итог сопряжения,
аварийный код, удаление пары, отказы принявшему. Уведомления из домена
(связь, версии, админ второго сервера) — domain/notices/reserve.py. Без точки в конце; имена и
адреса — как в остальных уведомлениях."""
from __future__ import annotations

from ..fmt import _e


def _n(name: str) -> str:
    return f"«{_e(name)}»"


def linked(peer: str, bot_username: str) -> str:
    link = (f'<a href="https://t.me/{_e(bot_username)}">@{_e(bot_username)}</a>' if bot_username
            else "бот второго сервера")
    return (f"✅ Резерв {_n(peer)} подключён — данные для переезда твоих пользователей уйдут к {_n(peer)} "
            f"в ближайшие минуты, шлюзы подключатся к нему сами\n\n"
            f"🛟 У тебя есть свой экран в боте {_n(peer)}: как он видит этот сервер и шлюзы, а если этот "
            f"сервер и все шлюзы упадут разом — ввод аварийного кода. Открой его сейчас, иначе в аварии он "
            f"не сможет тебе написать: {link}")


def code_issued(code: str) -> str:
    return ("🆘 <b>Аварийный код резерва</b>\n\n"
            f"<code>{_e(code)}</code>\n\n"
            "Сохрани его вне сервера: он нужен, только если сервер AWG и все шлюзы упадут разом — тогда "
            "его вводит админ этого сервера в боте резерва. Сообщение удалю через 10 минут; показать снова — "
            "«🛟 Резерв» → «🆘 Аварийный код»")


def code_renewed(code: str, why: str) -> str:
    return ("🆘 <b>Аварийный код резерва сменился</b> — " + _e(why) + "\n\n"
            f"<code>{_e(code)}</code>\n\n"
            "Прежний код больше не подходит. Сохрани новый вне сервера; показать снова — «🛟 Резерв» → "
            "«🆘 Аварийный код»")


def unpaired(peer: str) -> str:
    return f"ℹ️ Резерв {_n(peer)} удалён — линк пары снят, данные для переезда у него больше не обновляются"


def invite_expired(until: str) -> str:
    return f"⚠️ Приглашение в резерв не использовано за час, до {_e(until)} — строка больше не действует"


def code_refused(peer: str) -> str:
    return (f"⛔ Код от {_n(peer)} не совпал трижды — приглашение закрыто. Если код был верный, выпусти новое: "
            "«🛟 Резерв» → «📤 Пригласить»")


def refused_by_inviter(why: str) -> str:
    return {"expired": "⚠️ Срок приглашения вышел — попроси у админа второго сервера новое",
            "code": "⛔ Код не подтверждён трижды — второй сервер закрыл приглашение",
            "cancel": "ℹ️ Админ второго сервера отменил приглашение",
            "replaced": "ℹ️ Не актуально: второй сервер выпустил новое приглашение",
            "sessions": "⚠️ Слишком много подключений к приглашению — попроси новое",
            "nogw": "⛔ Ни у этого сервера, ни у второго нет шлюза с агентом новой линии — без шлюза переезд "
                    "невозможен ни в одну сторону. Подключи шлюз и попроси новое приглашение",
            }.get(why, "⚠️ Второй сервер отказал в подключении — попроси новое приглашение")
