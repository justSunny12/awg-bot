"""notices.py — тексты уведомлений резерва слоя бота: итог сопряжения,
аварийный код, удаление пары, отказы принявшему. Уведомления из домена
(связь, версии, админ второго сервера) — domain/notices/reserve.py. Без точки в конце; имена и
адреса — как в остальных уведомлениях."""
from __future__ import annotations

from ..fmt import _e
from .common import _n


def linked(peer: str, bot_username: str) -> str:
    link = (f'<a href="https://t.me/{_e(bot_username)}">@{_e(bot_username)}</a>' if bot_username
            else "бот второго сервера")
    return (f"✅ Резерв {_n(peer)} успешно подключён\n\n"
            "Синхронизация зашифрованных данных начнётся в течение нескольких минут, шлюзы подключатся автоматически.\n\n"
            "🛟 В боте резерва для тебя доступна отдельная панель администратора: там отображается статус связи с "
            "этим сервером и шлюзами, а также форма ввода аварийного кода.\n\n"
            "⚠️ Обязательно запусти бота резерва прямо сейчас, отправив /start — без этого он не сможет присылать "
            f"критические оповещения об авариях: {link}")


def code_issued(code: str) -> str:
    return ("🆘 <b>Аварийный код резерва</b>\n\n"
            f"<code>{_e(code)}</code>\n\n"
            "Сохрани этот код в надёжном месте вне сервера. Он понадобится для ручного ввода в боте резерва, если "
            "основной сервер выйдет из строя, а автоматический кворум не наберёт голосов.\n\n"
            "⏳ Сообщение будет удалено через 10 минут.\n\n"
            "Посмотреть код повторно: «🛟 Резерв» ➔ «🆘 Аварийный код»")


def code_mailed(addr: str) -> str:
    """Хвост сообщения с кодом после «✉️ Отправить на e-mail»."""
    return f"✉️ Аварийный код отправлен на <code>{_e(addr)}</code>"


def code_renewed(code: str, why: str) -> str:
    return ("🆘 <b>Аварийный код резерва сменился</b> — " + _e(why) + "\n\n"
            f"<code>{_e(code)}</code>\n\n"
            "Прежний код больше не подходит. Сохрани новый вне сервера; показать снова — «🛟 Резерв» → "
            "«🆘 Аварийный код»")


def unpaired(peer: str) -> str:
    return f"ℹ️ Резерв {_n(peer)} удалён — линк пары снят, данные для переезда у него больше не обновляются"


def invite_expired(until: str) -> str:
    return f"⚠️ Приглашение в резерв не использовано за час, до {_e(until)} — строка больше не действует"


