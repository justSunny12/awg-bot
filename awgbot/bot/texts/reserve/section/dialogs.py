"""dialogs.py — часть пакета section (см. __init__): диалоги удаления пары и
выключения готовности, экран «🆘 Аварийный код» и смена кода."""
from __future__ import annotations

from ...fmt import _e
from ..common import _n, _when


def unpair_dialog(name: str, rfpeer: dict | None = None) -> str:
    tail = ""
    r = rfpeer or {}
    if r.get("use"):                                          # Т-РТ5: мой РФ-доступ идёт через его шлюзы
        tail = f"\n\nСейчас РФ-доступ твоих пользователей идёт через шлюзы {_n(name)} — после удаления его не будет, пока не ответит свой шлюз"
    elif r.get("peer_use"):                                   # Т-РТ5: его РФ-доступ идёт через мои
        tail = f"\n\nСейчас через твои шлюзы идёт РФ-доступ пользователей {_n(name)} — после удаления у них он пропадёт"
    return (f"🗑 <b>Удалить резерв {_n(name)}?</b>\n\n"
            f"Линк пары снимется, данные для переезда у {_n(name)} перестанут обновляться, его точка ключа и "
            "экран администратора второго сервера в этом боте — прочь. Второй сервер получит уведомление, когда будет на "
            "связи. Подключить заново можно только новым приглашением" + tail)


def ready_off_dialog(name: str) -> str:
    return (f"☑️ <b>Выключить «Готов быть резервом»?</b>\n\n"
            f"Выключение действует в обе стороны: ни ты не примешь пользователей {_n(name)}, ни он твоих. "
            "Пока идёт переезд, выключение вступит после возврата")


def emergency_text(has_code: bool, shown_at: str) -> str:
    lines = ["🆘 <b>Аварийный код</b>", "",
             "Позволяет запустить экстренный переезд вручную, если кворум узлов не собрался (основной сервер "
             "недоступен, а голосов от шлюзов недостаточно). В этом случае код вводится администратором прямо в "
             "боте резерва.", "",
             "Код представляет собой часть мастер-ключа: без него резерв не сможет расшифровать базу и "
             "поднять сервисы.", "",
             "<b>Смена кода:</b> генерируется заново после каждого ручного переезда или принудительно по кнопке ниже."]
    if has_code:
        lines += ["", "Показанный код удаляется из чата через 10 минут" + (f"; последний показ — {_e(_when(shown_at))}" if shown_at else "")]
    else:
        lines += ["", "⚠️ Кода нет — он появится после подключения резерва"]
    return "\n".join(lines)


def new_code_dialog(name: str) -> str:
    return (f"🔄 <b>Сменить аварийный код?</b>\n\n"
            f"Текущий код аннулируется сразу: его парная часть на сервере {_n(name)} обновится автоматически в течение "
            "нескольких минут. Ключи и доступы шлюзов останутся прежними.\n"
            "Новый код пришлю отдельным сообщением")
