def accept_dialog(peer: str, host: str, version: str, *, rf_via_mine: bool, has_gateway: bool,
                  warn: list[str], ask_version: bool) -> str:
    # имя второго сервера приглашение не несёт — без имени он «удалённый сервер», без кавычек
    n = _n(peer) if peer else "удалённый сервер"
    n_gen = _n(peer) if peer else "удалённого сервера"    # родительный: сбой …, администратору …
    lines = [f"🛟 <b>Стать резервом для {n_gen}?</b>",
             f"<code>{_e(host)}</code> · v{_e(version)}", "",
             f"Если {n} перестанет отвечать, его бот и пользователи временно переключатся на твой сервер.\n"
             "Резервная копия хранится в зашифрованном виде. Ключ станет доступен, только если:\n"
             f"• большинство узлов сети подтвердят сбой {n_gen};\n"
             "• его администратор подтвердит передачу ключа вручную;\n"
             "• использован аварийный код.\n"
             "Твой сервер предоставляет только VPN-трафик и среду для работы бота. Управлять чужими пользователями "
             "нельзя: их сессии хранятся исключительно в оперативной памяти бота и сбрасываются после "
             f"восстановления {n_gen}.", "",
             "Связка взаимна: при падении твоего сервера твои пользователи и бот перейдут к нему."]
    if has_gateway:
        lines += ["", ("✅" if rf_via_mine else "☑️") + f" РФ-доступ пользователей {n_gen} через твои шлюзы, "
                  "если его шлюзы не отвечают"]
    for w in warn:
        lines += ["", "⚠️ " + _e(w)]
    if ask_version:
        lines += ["", f"⚠️ <b>Версия {n_gen} новее (v{_e(version)})</b>\n"
                  "Твой сервер использует более старую версию, поэтому не сможет принять чужих пользователей до "
                  "обновления. Твои пользователи переехать на резерв смогут.", "", "Продолжить подключение?"]
    lines += ["", f"Сгенерирую код подтверждения — передай его администратору {n_gen}"]
    return "\n".join(lines)


def connecting(host: str) -> str:
    return f"🟡 Подключаюсь к <code>{_e(host)}</code>…"


def no_answer(host: str, port: int) -> str:
    return (f"⚠️ Второй сервер не отвечает на <code>{_e(host)}</code>:<code>{port}</code> — проверь, что приглашение "
            "свежее и порт открыт у его провайдера")


