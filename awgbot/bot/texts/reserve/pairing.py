# ── Т-Р2: приглашение (пригласивший) ─────────────────────────────────────────

def invite_message(st: dict, token: str) -> str:
    until = until_text(st.get("expires") or "")
    head = ("🛟 <b>Приглашение в резерв</b>\n\n"
            "Перешли это сообщение администратору второго сервера AWG — он вставит строку ниже в своём боте: "
            "«⚙️ Настройки» → «🛟 Резерв» → «📥 Принять приглашение»\n\n"
            f"<code>{_e(token)}</code>\n\n"
            "Его бот покажет код подтверждения — администратор продиктует его тебе; введи код здесь кнопкой "
            f"«✏️ Ввести код». Приглашение действует час — до {_e(until)}")
    tail = invite_tail(st)
    return head + ("\n\n" + tail if tail else "")


def invite_tail(st: dict) -> str:
    ends = list(st.get("endpoints") or [])
    state = st.get("state") or ""
    if st.get("old_peer_version") and state not in ("connected", "accepted"):
        name = str(st.get("old_peer_name") or "")
        who = f"Сервер {_n(name)}" if name else "Удалённый сервер"
        return (f"⛔ {who} пытался подключиться с версии <b>v{_e(st['old_peer_version'])}</b>. Для резервирования оба "
                "сервера должны использовать версию не ниже v4.2.0.\n\n"
                "Попроси администратора обновить приложение и повторить попытку. Ссылка-приглашение остаётся активной")
    if len(ends) > 1:
        return (f"⚠️ К приглашению подключались с двух адресов: <code>{_e(ends[-2])}</code> и "
                f"<code>{_e(ends[-1])}</code>. Если один из них не резерва — отмени приглашение и выпусти новое")
    if state in ("connected", "accepted") and ends:
        if int(st.get("sessions") or 0) > 1:
            return f"🟢 Резерв подключился заново с адреса <code>{_e(ends[-1])}</code> — код сменился, попроси новый"
        return f"🟢 Резерв подключился с адреса <code>{_e(ends[-1])}</code> — попроси у его администратора код и введи его"
    return ""


