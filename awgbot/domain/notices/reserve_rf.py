"""reserve_rf.py — часть пакета notices (см. __init__): РФ-доступ через второй
сервер (Т-РТ6…Т-РТ11) — админу просящего и админу транзитного. Правила — как
у reserve; объём «(↑ … | ↓ …)», нули не выводим."""
from __future__ import annotations

from .reserve_fmt import _e, _n, _when


# ── РФ-доступ через второй сервер (Т-РТ6…Т-РТ11, на вычитку) ────────────────

def rf_transit_on(reserve: str, since: str, until: str) -> str:
    """Т-РТ6 (админу просящего, без звука): РФ-доступ пошёл через шлюзы второго сервера."""
    return (f"🔁 РФ-доступ — через шлюзы {_n(reserve)}: свои шлюзы не отвечают с {_when(since)}\n"
            f"Исходящий адрес у пользователей сменился — российские приложения могут попросить войти заново. "
            f"Ответит свой шлюз — трафик вернётся на него сам, не раньше {_when(until)}")


def rf_transit_back(reserve: str, own: str, label: str = "") -> str:
    """Т-РТ7 (админу просящего, без звука): РФ-доступ снова через свой шлюз — «Имя» (подпись), как везде."""
    who = (f" {_n(own)}" if own else "") + (f" ({_e(label)})" if own and label else "")
    return f"🟢 РФ-доступ снова через свой шлюз{who} — шлюзы {_n(reserve)} больше не нужны"


def rf_transit_lost(reserve: str, why: str) -> str:
    """Т-РТ8 (админу просящего, критичное): РФ-доступ через второй сервер прекратился, свои мертвы."""
    return (f"🔴 РФ-доступ через шлюзы {_n(reserve)} прекратился — {_e(why)}, а свои шлюзы не отвечают\n"
            "Российские сервисы временно открываются с зарубежного адреса и могут ругаться. Всё остальное и так шло мимо шлюза")


def rf_peer_use(primary: str, since: str) -> str:
    """Т-РТ10 (админу транзитного, без звука, один раз на эпизод)."""
    return (f"🇷🇺 РФ-доступ пользователей {_n(primary)} идёт через шлюзы этого сервера с {_when(since)}: шлюзы {_n(primary)} не отвечают\n"
            "Исходящий адрес у них — адрес твоего шлюза. Выключить — «🛟 Резерв» → «Мои шлюзы для резерва»")


def rf_peer_done(primary: str, up: int, dn: int) -> str:
    """Т-РТ11 (админу транзитного, без звука): эпизод кончился, объём за него (нули не выводим)."""
    from awgbot.util.textfmt.base import _updown
    head = f"🇷🇺 РФ-доступ {_n(primary)} снова идёт через его шлюзы"
    if not int(up or 0) and not int(dn or 0):
        return head
    return f"{head} — через твои прошло {_updown(int(up or 0), int(dn or 0))}"   # вид как на главной
