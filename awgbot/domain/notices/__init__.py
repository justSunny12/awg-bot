"""
notices/ — тексты уведомлений домена в одном месте.

Домен собирает Notification сам (продление, переезд, РФ-доступ, итог
обновления, месячные сбросы), и текст для них берёт отсюда, а не из слоя
бота: домен не тянет bot.texts. Бот показывает те же тексты на экранах —
bot/texts ре-экспортирует их под прежними именами, объекты одни и те же.
Зависимости текстов — только util/textfmt, core и util (замечание о шлюзе
сверяет вердикт с константами infra/routing).

Части: traffic — трафик, сроки, месячные сбросы; updates — итог self-update
и список изменений под катом; subscription — строка о днях паузы при
продлении; routing — замечание о шлюзе РФ-доступа и уведомления о выдаче и
отзыве доступа; gateway — причина отказа почты агента шлюза;
migration — поздравление с переездом и доклад о готовности; lanmap — адреса в
туннеле локальных сетей шлюзов: «выключены» и разовое уведомление после обновления.

Подмодули импортируются по имени (awgbot.domain.notices.traffic и т. п.),
общего входа через пакет нет намеренно: тексты грузятся и из бота, и из
сервисов при их загрузке, и каждый берёт только своё — без встречных циклов.
"""
