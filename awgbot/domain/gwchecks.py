"""
gwchecks.py — группы проверок агента шлюза, общие для домена и текстов.

Проверки монитора здоровья делятся на группы; часть из них не считается
аварией обвязки и не даёт уведомлений (свой стрик или просто не авария), а
их ⚪ «не проверено» не попадает в сводку панели — на экране монитора строка
остаётся. Домен (awgbot/domain/gateway.py) и тексты панели читают один список.
"""
CHECK_GROUPS_SOFT = ("lan", "svc", "own")        # не авария обвязки: локальная сеть, SMB соседей, свои списки
CHECK_GROUPS_QUIET_UNKNOWN = ("svc", "own")      # ⚪ этих групп не идёт в сводку панели

# Поломка на самом шлюзе при применении присланного (нет места, диск только
# для чтения): начало текста ошибки, по которому агент просит повтор, а
# карточка на ВПС пишет «⚠️ Шлюз «X»: …», а не «не смог принять».
WRITE_ERROR = "ошибка записи файла"


def failure_detail(head: str, err: str) -> str:
    """«не применились: <ошибка>»; при поломке на шлюзе — «не удалось
    применить. Ошибка записи файла: причина» (по вычитке 3.1.0)."""
    if err.startswith(WRITE_ERROR):
        return f"не удалось применить. {err[:1].upper()}{err[1:]}"
    return f"{head}: {err}"
