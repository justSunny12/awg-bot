# Хвост детали самопочиняющейся проверки: обвязку перевыставит сам агент
# (тик, политика аплинка). Такая строка — жёлтая и в счёт проблем не идёт:
# «🚑 Восстановить» по ней человек нажал бы зря.
SELF_HEAL_TAIL = "обвязка перевыставится в ближайшие минуты"
# Деталь проверки, которая ждёт первого автоматического тика (счётчики
# локальной сети): не проверено ещё, а не нечем проверить.
FIRST_TICK_DETAIL = "первый замер"


def check_mark(check) -> str:
    """Значок строки монитора: ✅ в порядке · 🔴 проблема (в том числе «нечем
    проверить» и «не запущен») · 🟡 ожидание — самопочинка, первый замер ·
    «не проверено» тихих групп (ожидание синхронизации; нет инструмента при
    включённой функции домен ставит ok=False — 🔴 и в счёт, решение 16.10.2026)
    · «» — функция выключена (check.off: sshd выключен в
    OMV, avahi-daemon без NAS) — строка на экран не идёт (решение 16.10.2026)."""
    if getattr(check, "off", False):
        return ""
    if check.ok:
        return "✅"
    detail = check.detail or ""
    if check.ok is False:
        return "🟡" if SELF_HEAL_TAIL in detail else "🔴"
    if detail == FIRST_TICK_DETAIL or getattr(check, "group", "") in CHECK_GROUPS_QUIET_UNKNOWN:
        return "🟡"
    return "🔴"


def health_problems(checks) -> list:
    """Проверки, которые считаются проблемами (🔴): их число — в шапке
    «🩺 Здоровье» и в сводке панели; порядок — как в замере."""
    return [c for c in checks if check_mark(c) == "🔴"]


# Поломка на самом шлюзе при применении присланного (нет места, диск только
# для чтения): начало текста ошибки, по которому агент просит повтор, а
# карточка на ВПС пишет «⚠️ Шлюз «X»: …», а не «не смог принять».
WRITE_ERROR = "ошибка записи файла"


def failure_detail(head: str, err: str) -> str:
    """«не применились: <ошибка>»; при поломке на шлюзе — «не удалось
    применить. Ошибка записи файла: причина» (по вычитке 3.1.0)."""
    if err.startswith(WRITE_ERROR):
        return f"не удалось применить. {err[:1].upper()}{err[1:]}"
    return f"{head}: {err}"
