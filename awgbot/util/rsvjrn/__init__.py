"""
rsvjrn — эпоха и журнал данных взаимного резерва серверов: нижний слой без
сервисов (реестр классов данных, временные триггеры соединения).

Право менять данные пользователей одной базы в каждый момент у одного
процесса — держателя эпохи (основа, пока её пользователи у неё; бот основы
на резерве, пока они там). Кто эпоху не держит, следует: запрет записи
решений стоит в самой базе — временные триггеры каждого соединения
(`triggers.install`) отказывают `RAISE(ABORT, 'jrn: …')`, и в Python отказ
приходит как `sqlite3.IntegrityError` с этим префиксом (`is_refusal`).

Пакет:
  classes   реестр классов данных (решение, маска, счётчик, местное …)
  triggers  временные триггеры: запрет записи решений у следующего и захват
            событий у держателя (захват — только при JSON-функциях SQLite)
  event     запечатка записей под K с открытым заголовком (события, хвост, пачки)
  segments  записи на диске: сегменты событий и файлы пачек счётчиков
  apply     применение событий держателя к базе следующего
  counts    поток счётчиков: пачки дельт, свёртка, повтор по номеру хоста
  opener    база бота основы на резерве по журналу — для процесса открытия
  rebase    перебазирование хвоста старой эпохи поверх базы держателя
"""
from __future__ import annotations

REFUSAL_PREFIX = "jrn:"


def json_ok(conn) -> bool:
    """Есть ли у SQLite JSON-функции: без них журнал не пишется, направление идёт
    прежним путём (пакет и слияние) — возможность пары jrn1 не объявляется."""
    try:
        return conn.execute("SELECT json_object('a', 1)").fetchone()[0] == '{"a":1}'
    except Exception:                                  # noqa: BLE001 — sqlite3.OperationalError: no such function
        return False


def is_refusal(exc: BaseException) -> bool:
    """Отказ базы «эпоха не у этого процесса» — а не конфликт уникальности."""
    return str(exc).startswith(REFUSAL_PREFIX)


def schema_too_old(exc: BaseException) -> bool:
    """База без таблиц журнала (копия старше эпохи, сырое соединение в тестах) — а не
    ошибка базы: замок дольше busy_timeout или сбой диска так не глушат, иначе путь
    молча меняется (снимок вместо событий, «хвоста нет» при живом хвосте)."""
    import sqlite3
    return isinstance(exc, sqlite3.OperationalError) and "no such" in str(exc)
