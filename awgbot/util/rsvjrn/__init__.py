"""
rsvjrn — эпоха и журнал данных взаимного резерва серверов: нижний слой без
сервисов (реестр классов данных, временные триггеры соединения).

Право менять данные пользователей одной базы в каждый момент у одного
процесса — держателя эпохи (основа, пока её пользователи у неё; бот основы
на резерве, пока они там). Кто эпоху не держит, следует: запрет записи
решений стоит в самой базе — временные триггеры каждого соединения
(`triggers.install`) отказывают `RAISE(ABORT, 'jrn: …')`, и в Python отказ
приходит как `sqlite3.IntegrityError` с этим префиксом (`is_refusal`).

Пакет:
  classes   реестр классов данных (решение, маска, счётчик, местное …)
  triggers  генератор временных триггеров запрета по реестру и схеме
"""
from __future__ import annotations

REFUSAL_PREFIX = "jrn:"


def is_refusal(exc: BaseException) -> bool:
    """Отказ базы «эпоха не у этого процесса» — а не конфликт уникальности."""
    return str(exc).startswith(REFUSAL_PREFIX)
