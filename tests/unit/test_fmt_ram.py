"""Unit: строка памяти «занято/всего» для панелей — `ram_pair`
(awgbot/bot/texts/fmt.py).

Оба числа — всегда в МБ целыми, разряды узким неразрывным пробелом, единица
один раз — у последнего числа: «548/7 812 МБ». Ошибка здесь — админ читает
«1,31/8 ГБ» рядом с «1,5 ГБ» трафика и путает память с трафиком, или видит
«478 МБ/976 МБ» с единицей у каждого числа и «1 ГБ/976 МБ» со смешанными
единицами.
"""

import pytest

from awgbot.bot.texts.fmt import ram_pair

pytestmark = pytest.mark.unit

T = " "   # узкий неразрывный пробел между разрядами


@pytest.mark.parametrize("used, total, want", [
    (548, 7812, f"548/7{T}812 МБ"),        # пример из решения: единица — только у «всего»
    (1340, 7812, f"1{T}340/7{T}812 МБ"),   # занято больше гигабайта — всё равно МБ, без «1,31 ГБ»
    (478, 976, "478/976 МБ"),              # плата на 1 ГБ: как видит ядро, без округления до «1 ГБ»
    (300, 512, "300/512 МБ"),              # маленький сервер — единица один раз
    (0, 7812, f"0/7{T}812 МБ"),            # ничего не занято — «0», не пусто
    (1024, 1024, f"1{T}024/1{T}024 МБ"),   # ровно гигабайт не переключает единицу
])
def test_ram_pair_is_always_megabytes_with_one_unit(used, total, want):
    assert ram_pair(used, total) == want


def test_ram_pair_rounds_fractional_megabytes_to_whole():
    """Замер отдаёт дробные МБ — на панели целые: «548/7 812 МБ», не «548.4/…»."""
    assert ram_pair(548.4, 7812.0) == f"548/7{T}812 МБ"


def test_ram_pair_has_no_gigabytes_and_no_unit_before_the_slash():
    """Ни «ГБ», ни «МБ/» в строке — иначе возвращается смешение единиц."""
    for used, total in [(100, 512), (1536, 8192), (7000, 7812)]:
        s = ram_pair(used, total)
        assert "ГБ" not in s and "МБ/" not in s and s.endswith(" МБ"), s
