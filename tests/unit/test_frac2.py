"""Unit: `frac2` (awgbot/util/textfmt/base.py) — общая дробь для текстов:
две ЗНАЧАЩИЕ цифры после запятой, ведущие нули дроби не в счёт, хвостовые
нули долой, целое — без дроби, запятая как в русском.

Через него идут ТБ носителей, «занято» памяти, секунды задержки слота и
«свободно» диска на экране здоровья. Ошибка здесь — на одном экране «1,50»
рядом с «1,68», «0,00 с» вместо «0,0034 с» или «8,0» вместо «8».
"""

import pytest

from awgbot.util.textfmt.base import frac2

pytestmark = pytest.mark.unit


@pytest.mark.parametrize("value, want", [
    (1.5, "1,5"),            # хвостовой ноль не выводим
    (1.68, "1,68"),
    (0.0034, "0,0034"),      # ведущие нули дроби — не значащие
    (8, "8"),                # целое — без дроби
    (8.0, "8"),
    (0, "0"),
    (1.368, "1,37"),         # округление арифметическое до двух значащих
    (0.25, "0,25"),
    (1.5e-5, "0,000015"),
    (2.345, "2,35"),         # половина — вверх, не банковское
    (2.005, "2,005"),        # ведущие нули дроби и у «2,005»: значащие — «5» и дальше
    (0.999, "1"),            # округление дало целое — дроби нет
])
def test_frac2_keeps_two_significant_decimals(value, want):
    assert frac2(value) == want
