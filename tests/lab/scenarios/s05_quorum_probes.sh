#!/bin/bash
# s05_quorum_probes — зонды кворума резерва (концепт «кворум» §3.1, §11.2 этап quo-2): пространство
# awg-quo на голосующих, пиры-зонды и второй адрес на awg0 основы, ответчик бота основы, пробы.
#
# ЧЕРНОВИК: набросан по образцу s01_zone и s03_vote, на стенде не прогонялся целиком. Что нужно от
# стенда: топология topo.sh (A, B, G1, G2, inet, cA), модуль AmneziaWG, venv (~/venv). Ответчик здесь —
# tests/lab/quorum_node.py (ответчик правила лидера на UDP-сокете в пространстве A без Telegram и базы);
# зонды — пространство awg-quo, поднятое install/quorum-probe-setup.sh в пространствах B, G1, G2
# (QUO_NS=awg-quo-<узел>, один хост стенда).
#
# Проверяет:
#   1. --selftest скрипта зондов на модуле стенда: RESULT_SOCKET_AT_HOST=1 (сокет интерфейса, созданного у
#      хоста и перенесённого в пространство, остаётся у хоста) и RESULT_TUNNEL_PING=1;
#   2. awg0 «Alpha» на A: подсеть пользователей 10.8.1.0/24, второй адрес 169.254.88.1/26 отдельной строкой
#      Address (инвариант записи), пиры-зонды B (.4), G1 (.5), G2 (.6) — ровно один /32 каждый;
#   3. зонды в awg-quo на B, G1, G2 (quorum-probe-setup.sh --up): проба JSON {"q":1,"l":"a","g":1,"n":"b"|"a1"|"a2",
#      "e":0,"w":"new","s":N} доходит до ответчика 169.254.88.1:8789, ответ {"r":"lead","y":…,"v":3} доходит
#      до зонда; после трёх проб с трёх узлов y = 3;
#   4. с зонда наружу (ping 203.0.113.5 из awg-quo) и в подсеть пользователей (10.8.1.1) — отказ: в
#      пространстве нет маршрута по умолчанию, таблица awg_quo пускает только udp на ответчик;
#   5. пользователь cA (конфиг пользователя A) — на 169.254.88.1:8789 отказ: AllowedIPs его пира — его /32,
#      и файервол хоста A (таблица awg_bot_guard, правила ответчика) пускает к ответчику только с блока
#      линии; проба с подменённым узлом (n=a2 с адреса .5) — не в счёт (y не растёт);
#   6. агент 4.1.0 на G1 при поднятом awg-quo находит аплинк (uplink_interface не видит awgq*);
#   7. --down на G2 — y падает до 2 через окно W (40 с); --wipe снимает пространство.
set -u
HERE="$(cd "$(dirname "$0")/.." && pwd)"; ROOT="$(cd "$HERE/../.." && pwd)"
USER_="${SUDO_USER:-$(id -un)}"; HOME_="$(getent passwd "$USER_" | cut -d: -f6)"
PY="${LAB_PY:-$HOME_/venv/bin/python}"
SCRIPT="$ROOT/install/quorum-probe-setup.sh"

# ── 1. самопроверка скрипта зондов на модуле стенда ───────────────────────────────────────────────
out="$(sh "$SCRIPT" --selftest 2>&1)" || { echo "selftest скрипта зондов не прошёл: $out"; exit 1; }
printf '%s\n' "$out" | grep -q 'RESULT_SOCKET_AT_HOST=1' || { echo "сокет зонда не остался у хоста: $out"; exit 1; }
printf '%s\n' "$out" | grep -q 'RESULT_TUNNEL_PING=1' || { echo "туннель зонда не ожил: $out"; exit 1; }
echo "s05_quorum_probes: самопроверка скрипта зондов пройдена; остальное (пп. 2–7) — черновик, см. шапку"
exit 0
